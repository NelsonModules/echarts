% html = htmldoc(optionJson, scriptTag, opts)
%   Build a self-contained HTML document that renders one ECharts chart from the
%   given JSON option. 'scriptTag' loads the library (see library). 'opts'
%   fields: PageTitle, Width, Height (pixels; 0 fills the viewport), Theme
%   ('light'/'dark'), Toolbar (true adds PNG/SVG download buttons).
function html = htmldoc(optionJson, scriptTag, opts)
  if nargin < 3
    opts = struct();
  end
  pageTitle = getOpt(opts, 'PageTitle', 'Nelson echarts');
  width = getOpt(opts, 'Width', 0);
  height = getOpt(opts, 'Height', 0);
  toolbar = getOpt(opts, 'Toolbar', false);
  onready = char(getOpt(opts, 'OnReady', ''));
  dark = strcmp(getOpt(opts, 'Theme', 'light'), 'dark');
  if dark
    bg = '#1e1e1e';
    fg = '#e6e6e6';
    themeArg = '"dark"';
  else
    bg = '#ffffff';
    fg = '#333333';
    themeArg = 'null';
  end
  if width > 0 && height > 0
    wrapStyle = sprintf(['box-sizing:border-box;width:%dpx;height:%dpx;', ...
      'margin:0 auto;'], round(width), round(height));
  else
    wrapStyle = 'box-sizing:border-box;width:100%;height:100%;';
  end
  safe = strrep(optionJson, '</', '<\/');
  if isempty(onready)
    readyScript = '';
  else
    readyScript = ['    try { (function(chart, echarts){', newline, ...
      onready, newline, ...
      '    }).call(null, chart, echarts); } catch (e) { console.error(e); }'];
  end
  toolbarHtml = {};
  if toolbar
    toolbarHtml = {['<div id="echarts-toolbar" style="padding:6px 12px;', ...
      'font-family:sans-serif;font-size:13px;">', ...
      '<button type="button" onclick="_dlPng()">Download PNG</button> ', ...
      '<button type="button" onclick="_dlSvg()">Download SVG</button></div>']};
  end
  lines = [{ ...
    '<!DOCTYPE html>'; ...
    '<html lang="en">'; ...
    '<head>'; ...
    '<meta charset="utf-8">'; ...
    '<meta name="viewport" content="width=device-width, initial-scale=1">'; ...
    ['<title>', escapehtml(pageTitle), '</title>']; ...
    '<style>'; ...
    ['html,body{margin:0;padding:0;height:100%;background:', bg, ';color:', fg, ';}']; ...
    ['#echarts-wrap{', wrapStyle, '}']; ...
    '</style>'; ...
    scriptTag; ...
    '</head>'; ...
    '<body>'}; ...
    toolbarHtml; ...
    {['<div id="echarts-wrap" role="img" aria-label="', escapehtml(pageTitle), ...
      '"></div>']; ...
    '<script>'; ...
    '(function(){'; ...
    reviver(); ...
    ['  var option = _revive(', safe, ');']; ...
    '  var chart = null;'; ...
    '  function start(){'; ...
    '    if (typeof echarts === "undefined") { return; }'; ...
    '    if (window.__nlsRegisterMap) { window.__nlsRegisterMap(); }'; ...
    ['    chart = echarts.init(document.getElementById("echarts-wrap"), ', themeArg, ', {renderer: "canvas"});']; ...
    '    chart.setOption(option);'; ...
    readyScript; ...
    '    window.addEventListener("resize", function(){ chart.resize(); });'; ...
    '    if (window.ResizeObserver) {'; ...
    '      new ResizeObserver(function(){ chart.resize(); }).observe(document.getElementById("echarts-wrap"));'; ...
    '    }'; ...
    '  }'; ...
    '  window._dlPng = function(){ if(!chart){return;} var a=document.createElement("a");'; ...
    ['    a.href=chart.getDataURL({type:"png",pixelRatio:2,backgroundColor:"', bg, '"});']; ...
    '    a.download="chart.png";a.click(); };'; ...
    '  window._dlSvg = function(){ if(!chart){return;}'; ...
    ['    var sv=echarts.init(document.createElement("div"),', themeArg, ',{renderer:"svg",width:chart.getWidth(),height:chart.getHeight()});']; ...
    '    sv.setOption(option); var s=sv.renderToSVGString(); sv.dispose();'; ...
    '    var b=new Blob([s],{type:"image/svg+xml"}); var a=document.createElement("a");'; ...
    '    a.href=URL.createObjectURL(b); a.download="chart.svg"; a.click(); };'; ...
    '  if (document.readyState === "complete" || document.readyState === "interactive") {'; ...
    '    start();'; ...
    '  } else {'; ...
    '    window.addEventListener("DOMContentLoaded", start);'; ...
    '  }'; ...
    '})();'; ...
    '</script>'; ...
    '</body>'; ...
    '</html>'}];
  html = strjoin(lines, newline);
end
%=============================================================================
function value = getOpt(opts, name, default)
  if isstruct(opts) && isfield(opts, name) && ~isempty(opts.(name))
    value = opts.(name);
  else
    value = default;
  end
end
