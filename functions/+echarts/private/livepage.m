% html = livepage(scriptTag, bg, themeArg)
%   Build the HTML page embedded in a uihtml component for live rendering. The
%   page reads the ECharts option from the component Data, (re)builds the chart
%   whenever Data changes, forwards data-point clicks and hovers to the engine,
%   answers image requests, and reports readiness. 'scriptTag' loads the
%   library; 'bg' is the page background color; 'themeArg' is the ECharts theme
%   JS argument ('null' or '"dark"').
function html = livepage(scriptTag, bg, themeArg)
  if nargin < 2 || isempty(bg)
    bg = '#ffffff';
  end
  if nargin < 3 || isempty(themeArg)
    themeArg = 'null';
  end
  lines = { ...
    '<!DOCTYPE html>'; ...
    '<html lang="en">'; ...
    '<head>'; ...
    '<meta charset="utf-8">'; ...
    '<style>'; ...
    ['html,body{margin:0;padding:0;height:100%;background:', bg, ';}']; ...
    '#echarts-wrap{box-sizing:border-box;width:100%;height:100%;}'; ...
    '</style>'; ...
    scriptTag; ...
    '</head>'; ...
    '<body>'; ...
    '<div id="echarts-wrap"></div>'; ...
    '<script>'; ...
    'var _chart = null;'; ...
    'var _h = null;'; ...
    'var _ro = null;'; ...
    'var _lastHover = "";'; ...
    reviver(); ...
    'function _payload(p){'; ...
    '  return { seriesIndex: (p.seriesIndex==null?-1:p.seriesIndex),'; ...
    '    dataIndex: (p.dataIndex==null?-1:p.dataIndex),'; ...
    '    name: (p.name===undefined?null:p.name),'; ...
    '    seriesName: (p.seriesName===undefined?null:p.seriesName),'; ...
    '    componentType: (p.componentType===undefined?null:p.componentType),'; ...
    '    value: (p.value===undefined?null:p.value) };'; ...
    '}'; ...
    'function _wireEvents(){'; ...
    '  if (!_chart) { return; }'; ...
    '  _chart.on("click", function(p){'; ...
    '    if (!_h) { return; }'; ...
    '    _h.sendEventToNelson("pointClick", _payload(p));'; ...
    '  });'; ...
    '  _chart.on("mouseover", function(p){'; ...
    '    if (!_h) { return; }'; ...
    '    var key = p.seriesIndex + ":" + p.dataIndex;'; ...
    '    if (key === _lastHover) { return; }'; ...
    '    _lastHover = key;'; ...
    '    _h.sendEventToNelson("pointHover", _payload(p));'; ...
    '  });'; ...
    '  _chart.on("legendselectchanged", function(p){'; ...
    '    if (!_h) { return; }'; ...
    '    _h.sendEventToNelson("legendClick", { name: p.name });'; ...
    '  });'; ...
    '}'; ...
    'function _render(option){'; ...
    '  if (!option || typeof echarts === "undefined") { return; }'; ...
    '  option = _revive(option);'; ...
    '  if (window.__nlsRegisterMap) { window.__nlsRegisterMap(); }'; ...
    '  if (!_chart) {'; ...
    ['    var _el = document.getElementById("echarts-wrap");']; ...
    ['    _chart = echarts.init(_el, ', themeArg, ', {renderer: "canvas"});']; ...
    '    _wireEvents();'; ...
    '    if (window.ResizeObserver) {'; ...
    '      _ro = new ResizeObserver(function(){ if (_chart) { _chart.resize(); } });'; ...
    '      _ro.observe(_el);'; ...
    '    }'; ...
    '  }'; ...
    '  _chart.setOption(option, { notMerge: true });'; ...
    '}'; ...
    'function setup(h){'; ...
    '  _h = h;'; ...
    '  window._h = h;'; ...
    '  h.addEventListener("DataChanged", function(){ _render(h.Data); });'; ...
    '  window.addEventListener("resize", function(){ if (_chart) { _chart.resize(); } });'; ...
    '  h.addEventListener("print", function(){ window.print(); });'; ...
    '  h.addEventListener("requestImage", function(e){'; ...
    '    var o = (e && e.Data) || {};'; ...
    '    if (!_chart) { h.sendEventToNelson("image", { data: "" }); return; }'; ...
    '    var url = _chart.getDataURL({ type: "png",'; ...
    '      pixelRatio: (o.scale || 2),'; ...
    ['      backgroundColor: (o.background || "', bg, '") });']; ...
    '    h.sendEventToNelson("image", { data: url });'; ...
    '  });'; ...
    '  h.addEventListener("copyImage", function(){'; ...
    '    if (!_chart || !navigator.clipboard || !window.ClipboardItem) { return; }'; ...
    '    var url = _chart.getDataURL({ type: "png", pixelRatio: 2 });'; ...
    '    fetch(url).then(function(r){ return r.blob(); }).then(function(b){'; ...
    '      try { navigator.clipboard.write([new ClipboardItem({ "image/png": b })]); } catch (e) {}'; ...
    '    });'; ...
    '  });'; ...
    '  _render(h.Data);'; ...
    '  h.sendEventToNelson("ready", {});'; ...
    '}'; ...
    '</script>'; ...
    '</body>'; ...
    '</html>' };
  html = strjoin(lines, newline);
end
