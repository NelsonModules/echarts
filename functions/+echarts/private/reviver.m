% js = reviver()
%   JavaScript source of the _revive function used by the rendered pages: it
%   walks a parsed ECharts option and turns any string marked with the '@js:'
%   prefix (produced by echarts.fn) back into a real function, so option fields
%   such as label formatters and tooltip callbacks can carry JavaScript.
function js = reviver()
  lines = { ...
    '  function _revive(v){'; ...
    '    if (v && typeof v === "object"){'; ...
    '      if (Array.isArray(v)){ for (var i=0;i<v.length;i++){ v[i]=_revive(v[i]); } return v; }'; ...
    '      for (var k in v){ if (Object.prototype.hasOwnProperty.call(v,k)){ v[k]=_revive(v[k]); } }'; ...
    '      return v;'; ...
    '    }'; ...
    '    if (typeof v === "string" && v.indexOf("@js:")===0){'; ...
    '      try { return (0,eval)("(" + v.slice(4) + ")"); } catch (e){ return v; }'; ...
    '    }'; ...
    '    return v;'; ...
    '  }' };
  js = strjoin(lines, newline);
end
