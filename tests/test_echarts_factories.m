% Every factory builds an echarts.chart whose first series has the expected type.
cases = { ...
  echarts.bar({'a', 'b'}, [1 2]),                      'bar'; ...
  echarts.line({'a', 'b'}, [1 2]),                     'line'; ...
  echarts.area({'a', 'b'}, [1 2]),                     'line'; ...
  echarts.scatter(1:3, [4 5 6]),                       'scatter'; ...
  echarts.bubble([1 2], [3 4], [5 6]),                 'scatter'; ...
  echarts.plot(1:3, [1 2 3]),                          'line'; ...
  echarts.pie({'a', 'b'}, [3 7]),                      'pie'; ...
  echarts.doughnut({'a', 'b'}, [3 7]),                 'pie'; ...
  echarts.funnel({'a', 'b'}, [3 7]),                   'funnel'; ...
  echarts.radar({'x', 'y', 'z'}, [1 2 3]),             'radar'; ...
  echarts.gauge(50),                                   'gauge'; ...
  echarts.heatmap(magic(3)),                           'heatmap'; ...
  echarts.boxplot(randn(20, 2)),                       'boxplot'; ...
  echarts.candlestick({'a', 'b'}, [1 2 0 1; 2 3 1 2]), 'candlestick'; ...
  echarts.sankey({'a'}, {'b'}, 5),                     'sankey'; ...
  echarts.graph({'a', 'b'}, [1 2]),                    'graph'; ...
  echarts.treemap({struct('name', 'a', 'value', 1)}),  'treemap'; ...
  echarts.sunburst({struct('name', 'a', 'value', 1)}), 'sunburst'; ...
  echarts.parallel({'a', 'b'}, [1 2; 3 4]),            'parallel'; ...
  echarts.effectScatter([1 2], [3 4]),                 'effectScatter'; ...
  echarts.pictorialBar({'a', 'b'}, [1 2]),             'pictorialBar'; ...
  echarts.hist(randn(1, 100), 10),                     'bar'; ...
  echarts.polar({'a', 'b'}, [1 2]),                    'bar'; ...
  echarts.lines({[0 0; 1 1; 2 0]}),                    'lines'; ...
  echarts.map({'France'}, 10),                         'map'; ...
  echarts.surface(magic(5)),                           'surface'; ...
  echarts.scatter3D([1 2 3], [4 5 6], [7 8 9]),        'scatter3D'; ...
  echarts.bar3D(magic(4)),                             'bar3D'; ...
  echarts.line3D([1 2 3], [4 5 6], [7 8 9]),           'line3D'; ...
  echarts.stem(0:5, sin(0:5)),                         'bar'; ...
  echarts.calendar({'2024-01-01', '2024-02-01'}, [1 2]), 'heatmap'; ...
  echarts.choropleth({'France', 'China'}, [10 40]),    'map'; ...
  echarts.wordcloud({'a', 'b'}, [2 1]),                'wordCloud'; ...
  echarts.themeRiver({'2024-01-01', '2024-02-01'}, [1 2], {'x', 'x'}), 'themeRiver'; ...
};
for k = 1:size(cases, 1)
  c = cases{k, 1};
  assert_isequal(class(c), 'echarts.chart');
  assert_isequal(c.config().series{1}.type, cases{k, 2});
  % Every chart serializes to a parseable ECharts option.
  decoded = jsondecode(c.json());
  assert_istrue(isfield(decoded, 'series'));
end
%=============================================================================
% tree takes a nested struct; its series type is 'tree'.
root = struct('name', 'r', 'children', {{struct('name', 'a')}});
assert_isequal(echarts.tree(root).config().series{1}.type, 'tree');
